/**
 * Config plugin de SSL pinning para Kobrax (EPIC-F2b historia 15).
 *
 * REQUIERE DEV BUILD / PREBUILD (EAS o `expo prebuild`). NO funciona en Expo Go, porque
 * inyecta configuración nativa (Android network-security-config + iOS NSPinnedDomains).
 *
 * QUÉ SE PINNEA: la clave pública (SPKI SHA-256, base64) de la(s) CA **intermedia/raíz** de la
 * cadena, NUNCA la hoja. La hoja la emite Let's Encrypt y rota cada ~60-90 días. Ver
 * docs/security/SSL-PINNING-MOVIL.md (pins vigentes, cómo recalcularlos, rotación).
 *
 * Opciones (app.json → plugins → ["./plugins/with-ssl-pinning", { ... }]):
 *   domain             host a pinnear, sin esquema ni ruta (ej. "api.kobrax.ikigaisystems.lat")
 *   pins               array de >=2 pins distintos: base64 de 32 bytes (se acepta prefijo "sha256/")
 *   expiration         "YYYY-MM-DD" (recomendado). Pasada esa fecha Android deja de exigir el pin
 *                      (válvula de seguridad: la app vuelve a validar solo con la CA del sistema).
 *                      iOS no soporta expiración.
 *   includeSubdomains  default true
 *   ios                default true; false = no tocar Info.plist
 *   enabled            false = no hace nada (dev). Default true.
 *
 * Comportamiento:
 *   - enabled:false            -> NO-OP explícito (aviso).
 *   - sin `pins` (vacío)       -> NO-OP con advertencia fuerte. Si KOBRAX_REQUIRE_SSL_PINNING=1
 *                                 (ponerlo en builds de producción) falla el build.
 *   - cualquier otra config inválida -> THROW (nunca se degrada en silencio).
 *   - Si ya existe un network_security_config.xml que NO generó este plugin -> THROW (no se pisa).
 */
const {
  withAndroidManifest,
  withDangerousMod,
  withInfoPlist,
  AndroidConfig,
} = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const TAG = '[with-ssl-pinning]';
const NSC_RESOURCE = 'network_security_config';
const GENERATED_MARKER = '<!-- generated by with-ssl-pinning (apps/mobile/plugins). No editar a mano. -->';
const HOSTNAME_RE = /^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/i;
const PIN_BYTES = 32;

/** Normaliza "sha256/XXXX" -> "XXXX". */
function bareDigest(pin) {
  return String(pin).trim().replace(/^sha256\//i, '');
}

/** Valida un host (sin esquema, ruta, puerto ni comodín). Devuelve el host en minúsculas. */
function validateDomain(domain) {
  if (typeof domain !== 'string' || domain.trim() === '') {
    throw new Error(`${TAG} \`domain\` es obligatorio para pinnear (recibido: ${JSON.stringify(domain)}).`);
  }
  const d = domain.trim().toLowerCase();
  if (!HOSTNAME_RE.test(d)) {
    throw new Error(
      `${TAG} \`domain\` inválido: "${domain}". Debe ser un host sin esquema, ruta, puerto ni comodín.`,
    );
  }
  return d;
}

/**
 * Valida y normaliza los pins: cada uno base64 canónico que decodifica a exactamente 32 bytes
 * (SHA-256), sin duplicados, mínimo 2. Devuelve el array normalizado (sin prefijo "sha256/").
 */
function validatePins(pins) {
  if (!Array.isArray(pins)) {
    throw new Error(`${TAG} \`pins\` debe ser un array de strings.`);
  }
  const out = [];
  for (const raw of pins) {
    if (typeof raw !== 'string') {
      throw new Error(`${TAG} pin inválido (no es string): ${JSON.stringify(raw)}.`);
    }
    const b = bareDigest(raw);
    const buf = Buffer.from(b, 'base64');
    if (!/^[A-Za-z0-9+/]+={0,2}$/.test(b) || buf.length !== PIN_BYTES || buf.toString('base64') !== b) {
      throw new Error(
        `${TAG} pin mal formado: "${raw}". Debe ser base64 de un SHA-256 (32 bytes, 44 caracteres).`,
      );
    }
    out.push(b);
  }
  if (new Set(out).size !== out.length) {
    throw new Error(`${TAG} hay pins duplicados; cada pin debe ser distinto.`);
  }
  if (out.length < 2) {
    throw new Error(
      `${TAG} se requieren al menos 2 pins distintos (uno vigente y uno de respaldo); recibidos: ${out.length}.`,
    );
  }
  return out;
}

/** Valida `expiration` (YYYY-MM-DD, fecha real y futura). `undefined` -> undefined. */
function validateExpiration(expiration, now = new Date()) {
  if (expiration === undefined || expiration === null || expiration === '') return undefined;
  if (typeof expiration !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(expiration)) {
    throw new Error(`${TAG} \`expiration\` debe tener formato YYYY-MM-DD (recibido: ${JSON.stringify(expiration)}).`);
  }
  const d = new Date(`${expiration}T00:00:00Z`);
  if (Number.isNaN(d.getTime()) || d.toISOString().slice(0, 10) !== expiration) {
    throw new Error(`${TAG} \`expiration\` no es una fecha real: ${expiration}.`);
  }
  if (d.getTime() <= now.getTime()) {
    throw new Error(
      `${TAG} \`expiration\` (${expiration}) ya pasó: el pin-set quedaría inactivo desde el primer día.`,
    );
  }
  return expiration;
}

/**
 * Resuelve las opciones crudas. Devuelve `{ active:false, reason }` o `{ active:true, domain, pins,
 * expiration, includeSubdomains, ios }`. Lanza si el pinning se pidió con configuración inválida.
 */
function resolveOptions(props = {}, env = process.env, now = new Date()) {
  const { enabled, domain, pins, expiration, includeSubdomains, ios } = props ?? {};
  if (enabled === false) {
    return { active: false, reason: 'disabled' };
  }
  const noPins = pins === undefined || pins === null || (Array.isArray(pins) && pins.length === 0);
  if (noPins) {
    if (env.KOBRAX_REQUIRE_SSL_PINNING === '1') {
      throw new Error(
        `${TAG} KOBRAX_REQUIRE_SSL_PINNING=1 pero no hay \`pins\`: el build de producción no puede salir sin pinning.`,
      );
    }
    return { active: false, reason: 'no-pins' };
  }
  return {
    active: true,
    domain: validateDomain(domain),
    pins: validatePins(pins),
    expiration: validateExpiration(expiration, now),
    includeSubdomains: includeSubdomains !== false,
    ios: ios !== false,
  };
}

/** Genera el XML del network-security-config. Función pura. */
function buildAndroidNetworkSecurityConfig({ domain, pins, expiration, includeSubdomains = true }) {
  const expAttr = expiration ? ` expiration="${expiration}"` : '';
  const pinTags = pins.map((p) => `        <pin digest="SHA-256">${p}</pin>`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
${GENERATED_MARKER}
<network-security-config>
    <domain-config cleartextTrafficPermitted="false">
        <domain includeSubdomains="${includeSubdomains ? 'true' : 'false'}">${domain}</domain>
        <trust-anchors>
            <certificates src="system"/>
        </trust-anchors>
        <pin-set${expAttr}>
${pinTags}
        </pin-set>
    </domain-config>
</network-security-config>
`;
}

/** Entrada de Info.plist para iOS. Función pura. */
function buildIosPinnedDomain({ pins, includeSubdomains = true }) {
  return {
    NSIncludesSubdomains: includeSubdomains,
    // NSPinnedCAIdentities: coincide con la clave pública de CUALQUIER CA (intermedia/raíz) de la
    // cadena validada, no con la hoja. Es lo coherente con pinnear intermedias.
    NSPinnedCAIdentities: pins.map((p) => ({ 'SPKI-SHA256-BASE64': p })),
  };
}

/**
 * Decide qué hacer con el archivo NSC: lanza si existe uno ajeno; si es nuestro (o no existe),
 * devuelve el contenido a escribir. `existing` es el contenido actual o null.
 */
function resolveNscWrite(existing, generated) {
  if (existing != null && !existing.includes(GENERATED_MARKER)) {
    throw new Error(
      `${TAG} ya existe res/xml/${NSC_RESOURCE}.xml y no lo generó este plugin; no se sobrescribe. ` +
        'Fusiona a mano el <domain-config> con <pin-set> en ese archivo y desactiva el plugin ' +
        '(enabled:false), o elimina el archivo existente.',
    );
  }
  return generated;
}

function withAndroidSslPinning(config, opts) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      const file = path.join(xmlDir, `${NSC_RESOURCE}.xml`);
      const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      const content = resolveNscWrite(existing, buildAndroidNetworkSecurityConfig(opts));
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(file, content);
      return cfg;
    },
  ]);

  config = withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    const current = app.$['android:networkSecurityConfig'];
    if (current && current !== `@xml/${NSC_RESOURCE}`) {
      throw new Error(
        `${TAG} el manifest ya declara android:networkSecurityConfig="${current}"; no se sobrescribe.`,
      );
    }
    app.$['android:networkSecurityConfig'] = `@xml/${NSC_RESOURCE}`;
    return cfg;
  });

  return config;
}

function withIosSslPinning(config, opts) {
  return withInfoPlist(config, (cfg) => {
    const ats = cfg.modResults.NSAppTransportSecurity ?? {};
    ats.NSPinnedDomains = {
      ...(ats.NSPinnedDomains ?? {}),
      [opts.domain]: buildIosPinnedDomain(opts),
    };
    cfg.modResults.NSAppTransportSecurity = ats;
    return cfg;
  });
}

function withSslPinning(config, props = {}) {
  const opts = resolveOptions(props);
  if (!opts.active) {
    if (opts.reason === 'disabled') {
      console.warn(`${TAG} enabled:false -> pinning DESACTIVADO explícitamente (solo dev).`);
    } else {
      console.warn(
        `${TAG} ADVERTENCIA: sin \`pins\` -> pinning DESACTIVADO (NO-OP). Esta build NO valida la ` +
          'cadena contra pins. No usar para producción (ponga KOBRAX_REQUIRE_SSL_PINNING=1 para forzar el fallo).',
      );
    }
    return config;
  }
  if (!opts.expiration) {
    console.warn(
      `${TAG} sin \`expiration\`: el pin-set no caduca nunca. Recomendado fijar una fecha como válvula de rotación.`,
    );
  }
  config = withAndroidSslPinning(config, opts);
  if (opts.ios) config = withIosSslPinning(config, opts);
  return config;
}

module.exports = withSslPinning;
module.exports.default = withSslPinning;
module.exports.buildAndroidNetworkSecurityConfig = buildAndroidNetworkSecurityConfig;
module.exports.buildIosPinnedDomain = buildIosPinnedDomain;
module.exports.validatePins = validatePins;
module.exports.validateDomain = validateDomain;
module.exports.validateExpiration = validateExpiration;
module.exports.resolveOptions = resolveOptions;
module.exports.resolveNscWrite = resolveNscWrite;
module.exports.GENERATED_MARKER = GENERATED_MARKER;
